"use client"

/**
 * The demo's disclosure.
 *
 * A visitor deserves to know they are looking at captured output rather than a
 * live inference call — and saying so costs nothing, because what is on screen
 * is genuinely the models' work. The details panel breaks down where each
 * module's numbers came from, including the places where the honest answer is
 * "computed, not predicted" or "curated examples, not measured accuracy".
 *
 * The disclosure is not dismissible. A notice that a visitor can close is a
 * notice that is absent for most of the visit — someone who lands on a
 * forecast three pages in would have no way to know the numbers were
 * pre-computed. Only the details panel collapses.
 *
 * It is scoped to the company workspace, because that is the only route that
 * renders captured model output. The dashboard, news and account pages show
 * live Colombo Stock Exchange data, and claiming those numbers are
 * pre-computed would be its own kind of inaccuracy. (/risk, /predict and
 * /dividend only redirect into the workspace, so they need no notice of their
 * own.)
 */

import { useEffect, useRef, useState } from "react"
import { usePathname } from "next/navigation"
import { Info } from "lucide-react"
import { DEMO_MODE, loadDemoManifest, type DemoManifest } from "@/lib/demo/config"

const MODEL_DETAILS = [
  {
    label: "Price forecast",
    text: "Precomputed T+5 open-price ensemble outputs (LightGBM, XGBoost, CatBoost), with SHAP attributions.",
  },
  {
    label: "Dividend",
    text: "Precomputed dividend-cut model outputs, with investor explanations generated by Gemini.",
  },
  {
    label: "Financial health",
    text: "Precomputed financial-health results using Gemini-extracted CSE filing data, the Altman Z-Score model, and the SVR next-quarter Z-Score forecast.",
  },
  {
    label: "Risk statistics",
    text: "Market-risk statistics computed from real CSE closing prices for 274 companies. Beta is measured against ASPI; Sharpe uses a 9% risk-free rate. These are computed statistics, not model predictions.",
  },
  {
    label: "News sentiment",
    text: "A curated set of 20 examples selected from 30 candidates. These were captured while the service used its financial-lexicon fallback instead of the XGBoost classifier, which requires OpenAI embeddings. The examples do not represent measured model accuracy.",
  },
]

export function DemoBanner() {
  const pathname = usePathname()
  const [manifest, setManifest] = useState<DemoManifest | null>(null)
  const [expanded, setExpanded] = useState(false)
  const bannerRef = useRef<HTMLDivElement>(null)

  const onCompanyPage = pathname?.startsWith("/company/") ?? false

  useEffect(() => {
    if (!DEMO_MODE || !onCompanyPage) return
    loadDemoManifest().then(setManifest)
  }, [onCompanyPage])

  useEffect(() => {
    if (!expanded) return

    const handleClickOutside = (event: MouseEvent | TouchEvent) => {
      if (bannerRef.current && !bannerRef.current.contains(event.target as Node)) {
        setExpanded(false)
      }
    }

    const handleKeyDown = (event: KeyboardEvent) => {
      if (event.key === "Escape") {
        setExpanded(false)
      }
    }

    document.addEventListener("mousedown", handleClickOutside)
    document.addEventListener("touchstart", handleClickOutside)
    document.addEventListener("keydown", handleKeyDown)

    return () => {
      document.removeEventListener("mousedown", handleClickOutside)
      document.removeEventListener("touchstart", handleClickOutside)
      document.removeEventListener("keydown", handleKeyDown)
    }
  }, [expanded])

  if (!DEMO_MODE || !onCompanyPage) return null

  return (
    <div
      ref={bannerRef}
      className="border-b border-amber-500/30 bg-amber-500/10 text-amber-950 dark:text-amber-100"
    >
      <div className="mx-auto flex max-w-7xl items-start gap-2.5 px-4 py-2 text-sm">
        <Info className="mt-0.5 h-4 w-4 shrink-0" />

        <div className="min-w-0 flex-1">
          {!expanded ? (
            <p className="leading-snug">
              <span className="font-semibold">About this deployment:</span>{" "}
              <button
                type="button"
                onClick={() => setExpanded(true)}
                className="font-medium underline underline-offset-2 hover:no-underline ml-1"
              >
                More details
              </button>
            </p>
          ) : (
            <div className="space-y-3">
              <div className="flex items-start justify-between gap-4">
                <p className="leading-relaxed">
                  <span className="font-semibold">About this deployment:</span>{" "}
                  This deployment showcases InvestWise&apos;s financial analytics capabilities using precomputed model outputs and metrics where noted. Some backend services are not continuously running in this hosted environment. Live market data, including CSE indices, prices, and news, is fetched separately from the Colombo Stock Exchange.
                </p>
                <button
                  type="button"
                  onClick={() => setExpanded(false)}
                  className="shrink-0 font-medium underline underline-offset-2 hover:no-underline text-xs sm:text-sm"
                >
                  Hide details
                </button>
              </div>

              <div className="border-t border-amber-500/25 pt-2.5 space-y-2">
                <div>
                  <h4 className="font-semibold text-xs uppercase tracking-wider text-amber-900/90 dark:text-amber-200/90">
                    Data and model details
                  </h4>
                  <p className="text-xs opacity-75 mt-0.5">
                    Collapsed by default; expand for the technical details.
                  </p>
                </div>

                <dl className="space-y-2 text-xs sm:text-sm">
                  {MODEL_DETAILS.map((row) => (
                    <div key={row.label} className="sm:flex sm:gap-3">
                      <dt className="font-medium sm:w-36 sm:shrink-0 text-amber-950 dark:text-amber-100">
                        {row.label}
                      </dt>
                      <dd className="opacity-90 leading-relaxed">{row.text}</dd>
                    </div>
                  ))}
                </dl>

                {manifest?.counts && (
                  <div className="pt-2 text-xs opacity-75 border-t border-amber-500/15">
                    Captured dataset coverage: {manifest.counts.predict} price ensemble models · {manifest.counts.dividend} dividend evaluations · {manifest.counts.health} filing pipelines · {manifest.counts.sentiment} curated sentiment cases.
                  </div>
                )}
              </div>
            </div>
          )}
        </div>
      </div>
    </div>
  )
}
